/*
 * Assembles a Playwright spec from a passing run: each step's comment, then the lines the Acme
 * driver recorded while it carried the step out (src/acme/driver.ts).
 */

/** A step of a passing run: what was written, and the Playwright lines that repeat it. */
export interface RecordedStep {
  text: string;
  lines: string[];
}

/** The text of a `.spec.ts` file that repeats a passing run without the model. */
export function toSpec({ name, appUrl, steps }: { name: string; appUrl: string; steps: RecordedStep[] }) {
  const body = steps.flatMap(({ text, lines }) => [`  // ${text.replace(/\s+/g, ' ')}`, ...lines.map((l) => `  ${l}`)]);
  return `import { test, expect } from '@playwright/test';

// Generated by Needle Test Studio from a plain-English test case run against Acme Admin.
// APP_URL is where a path like /login is appended.
const APP_URL = process.env.APP_URL ?? ${JSON.stringify(appUrl)};

test(${JSON.stringify(name)}, async ({ page }) => {
  await page.goto(APP_URL + "/login");
${body.join('\n')}
});
`;
}
